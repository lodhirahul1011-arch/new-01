export function translateLiteral(language: AppLanguage, value: string) {
  const trimmed = value.trim();
  const direct = resolveTranslation(language, value);
  if (direct) return direct;

  const dynamic = translateDynamicLiteral(language, value);
  if (dynamic !== value) return dynamic;

  const normalizedKey = trimmed
    .replace(/&/g, 'and')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase();
  const normalized = resolveTranslation(language, trimmed, normalizedKey);
  if (normalized) return value.replace(trimmed, normalized);

  const key = englishLiteralKeys[trimmed];
  if (!key) return value;

  const translated = resolveTranslation(language, trimmed, key);
  return translated ? value.replace(trimmed, translated) : value;
}
