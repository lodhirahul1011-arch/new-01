function buildTranslationMap(
  language: AppLanguage,
  base: TranslationMap,
  extras: TranslationMap,
  locale: TranslationMap,
) {
  try {
    const merged = {
      ...locale,
      ...base,
      ...extras,
      ...screenLiteralTranslations[language],
      ...priorityScreenTranslations[language],
      ...accountSettingsTranslations[language],
    };
    logs.info('i18n translation map prepared', {
      language,
      localeKeys: Object.keys(locale).length,
      totalKeys: Object.keys(merged).length,
    });
    return merged;
  } catch (error) {
    logs.error('Failed to prepare i18n translation map', { language, error });
    return { ...base, ...extras };
  }
}

