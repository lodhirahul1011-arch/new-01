function buildEnglishLiteralMap() {
  try {
    const localeLiterals = Object.entries(enLocale).reduce<TranslationMap>(
      (acc, [key, value]) => {
        if (key.startsWith('language_name_')) {
          return acc;
        }

        if (typeof value === 'string') {
          const trimmed = value.trim();
          if (trimmed && !acc[trimmed]) {
            acc[trimmed] = key;
          }
        }

        return acc;
      },
      {},
    );
    const merged = { ...localeLiterals, ...literalEnglish };
    logs.info('i18n English literal map prepared', {
      localeKeys: Object.keys(localeLiterals).length,
      totalKeys: Object.keys(merged).length,
    });
    return merged;
  } catch (error) {
    logs.error('Failed to prepare i18n English literal map', error);
    return literalEnglish;
  }
}

