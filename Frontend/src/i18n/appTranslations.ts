function escapeRegex(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function hasProtectedTerm(value: string, term: string) {
  return new RegExp(`\\b${escapeRegex(term)}\\b`, 'i').test(value);
}

function preserveProtectedTerms(source: string, translated: string) {
  try {
    return PROTECTED_I18N_TERMS.reduce((nextValue, term) => {
      if (!hasProtectedTerm(source, term) || hasProtectedTerm(nextValue, term)) {
        return nextValue;
      }

      logs.info('i18n preserved English technical term', { term, source });
      return `${nextValue} ${term}`.trim();
    }, translated);
  } catch (error) {
    logs.error('Failed to preserve i18n technical terms', {
      source,
      translated,
      error,
    });
    return translated;
  }
}

function resolveTranslation(
  language: AppLanguage,
  source: string,
  key?: string,
) {
  try {
    const translated = key
      ? appTranslations[language]?.[key]
      : appTranslations[language]?.[source];
    if (!translated || translated === key) {
      return undefined;
    }

    return preserveProtectedTerms(source, translated);
  } catch (error) {
    logs.error('Failed to resolve i18n translation', { language, source, key, error });
    return undefined;
  }
}

